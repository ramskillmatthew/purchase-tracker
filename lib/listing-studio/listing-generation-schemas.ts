import { z } from "zod";
// Type-only — erased at compile time, matching lib/listing-studio/auto-group-schemas.ts's
// own convention exactly: keeps this file pure and directly testable with
// no Anthropic runtime import (and no server-only restriction), while still
// type-checking LISTING_GENERATION_TOOL against the SDK's own Tool shape.
import type Anthropic from "@anthropic-ai/sdk";

/**
 * Milestone 4 (AI listing generation). Deliberately NOT the 5-pass
 * image_quality/label_extraction/visual_identification/consistency_check/
 * generation pipeline sketched in lib/listing-studio/ai-schemas.ts during
 * Stage 1 planning (confirmed unused by any real route) — this is a single,
 * direct structured-extraction call per already-created product group,
 * modelled on lib/listing-studio/auto-group-schemas.ts's established
 * conventions (strict zod schema, forced single tool call, re-validated
 * regardless).
 *
 * Critically, the AI NEVER returns a title or description — only
 * structured product fields. Title/description are always derived from
 * those fields by lib/listing-studio/listing-template.ts's pure functions,
 * never generated by, or independently editable from, the AI's own output.
 */

const fieldValueSchema = z.string().trim().min(1).max(150).nullable();
const confidenceSchema = z.enum(["high", "medium", "low"]);
const notesSchema = z.string().trim().min(1).max(500).nullable();

function structuredField<T extends z.ZodTypeAny>(valueSchema: T) {
  return z.object({ value: valueSchema, confidence: confidenceSchema }).strict();
}

// Milestone 4 sizing correction: the AI must never perform or invent a
// size-system conversion itself (lib/listing-studio/size-conversion.ts is
// the ONE place that happens, deterministically, brand-aware). This field
// bundles exactly what the model is allowed to report — which system was
// printed on the label, its raw value, and (only if the label itself
// states it) which gender — as one unit, since all three describe the same
// single size marking read off the same label. `system`/`value` are kept
// independently nullable (rather than requiring both-or-neither) so a
// response that's otherwise perfectly good isn't rejected outright over an
// inconsistent size read; the caller treats a partial pair (one set,
// the other null) as "no usable source size" rather than guessing.
// Milestone 4 sizing coverage correction: `gender` gained a 4th value,
// "childrens" — children's footwear uses an entirely different numbering
// scale from adult sizing (see lib/listing-studio/size-conversion.ts), so
// this must be reported explicitly rather than silently treated as an
// adult size. Still only ever reported when the label itself states it
// (e.g. "Kids"/"Youth"/"Toddler" wording, or a children's-specific size
// range) — never inferred from the shoe's general style.
const sourceSizeSchema = z.object({
  system: z.enum(["UK", "EU", "US"]).nullable(),
  value: z.string().trim().min(1).max(20).nullable(),
  gender: z.enum(["mens", "womens", "unisex", "childrens"]).nullable(),
  confidence: confidenceSchema,
}).strict();
export type SourceSize = z.infer<typeof sourceSizeSchema>;

export const listingGenerationFieldsSchema = z.object({
  brand: structuredField(fieldValueSchema),
  model: structuredField(fieldValueSchema),
  productType: structuredField(fieldValueSchema),
  colour: structuredField(fieldValueSchema),
  sourceSize: sourceSizeSchema,
  sku: structuredField(fieldValueSchema),
  notes: notesSchema,
}).strict();
export type ListingGenerationFields = z.infer<typeof listingGenerationFieldsSchema>;

