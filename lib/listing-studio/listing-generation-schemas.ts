/** Every way the listing-generation AI call can end — mirrors AutoGroupAiOutcome's
 * closed-set convention exactly, so a failure is always a safe, fixed,
 * pre-written category, never a raw provider error surfaced to the UI. */
export type ListingGenerationAiOutcome =
  | { status: "success"; data: ListingGenerationFields }
  | { status: "not_configured" }
  | { status: "request_failed" }
  | { status: "no_tool_call" }
  | { status: "invalid_output" };

export function describeListingGenerationFailure(status: Exclude<ListingGenerationAiOutcome["status"], "success">): string {
  switch (status) {
    case "not_configured": return "Listing generation is not available right now.";
    case "request_failed": return "Listing generation failed. Please try again.";
    case "no_tool_call": return "Listing generation did not return a structured result. Please try again.";
    case "invalid_output": return "Listing generation returned an unexpected result. Please try again.";
  }
}
